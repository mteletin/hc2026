    private static readonly FrozenDictionary<ulong, (char Ascii, bool Inverted)> BasicSignatures;
    private static readonly FrozenDictionary<uint, char> CpmSignatures;
    private static readonly ushort[][] Basic16x16Glyphs;
    private static readonly byte[][] Cpm8x16Glyphs;

    static CrispFontCatalog()
    {
        var basicDict = new Dictionary<ulong, (char Ascii, bool Inverted)>();
        var cpmDict = new Dictionary<uint, char>();
        var basicList = new ushort[96][];
        var cpmList = new byte[96][];

        var basicRom = Basic8x8RomFont;
        for (int i = 0; i < 96; i++)
        {
            var charCode = (char)(32 + i);
            var glyphSpan = basicRom.Slice(i * 8, 8);
            ulong sig = ComputeBasicSignature(glyphSpan);
            basicDict.TryAdd(sig, (charCode, false));
            // Inverse video mapping
            basicDict.TryAdd(~sig, (charCode, true));
            basicList[i] = GenerateBasic16x16(glyphSpan);
        }

        var cpmRom = Cpm4x8RomFont;
        for (int i = 0; i < 96; i++)
        {
            var charCode = (char)(32 + i);
            var glyphSpan = cpmRom.Slice(i * 8, 8);
            uint sig = ComputeCpmNibbleSignature(glyphSpan);
            cpmDict.TryAdd(sig, charCode);
            cpmList[i] = GenerateCpm8x16(glyphSpan);
        }

        // Typographic refinements for dense CP/M 4x8 glyphs in 8x16 (e.g. 'M', 'W')
        RefineDenseCpmGlyphs(cpmList);
        RefineBasic16x16Glyphs(basicList);

        BasicSignatures = basicDict.ToFrozenDictionary();
        CpmSignatures = cpmDict.ToFrozenDictionary();
        Basic16x16Glyphs = basicList;
        Cpm8x16Glyphs = cpmList;
    }

    public static ulong ComputeBasicSignature(ReadOnlySpan<byte> cell8Rows)
    {
        return ((ulong)cell8Rows[0] << 56) |
               ((ulong)cell8Rows[1] << 48) |
               ((ulong)cell8Rows[2] << 40) |
               ((ulong)cell8Rows[3] << 32) |
               ((ulong)cell8Rows[4] << 24) |
               ((ulong)cell8Rows[5] << 16) |
               ((ulong)cell8Rows[6] << 8)  |
               cell8Rows[7];
    }

    public static uint ComputeCpmNibbleSignature(ReadOnlySpan<byte> nibble8Rows)
    {
        return ((uint)(nibble8Rows[0] & 0x0F) << 28) |
               ((uint)(nibble8Rows[1] & 0x0F) << 24) |
               ((uint)(nibble8Rows[2] & 0x0F) << 20) |
               ((uint)(nibble8Rows[3] & 0x0F) << 16) |
               ((uint)(nibble8Rows[4] & 0x0F) << 12) |
               ((uint)(nibble8Rows[5] & 0x0F) << 8)  |
               ((uint)(nibble8Rows[6] & 0x0F) << 4)  |
               (uint)(nibble8Rows[7] & 0x0F);
    }

    public static bool MatchBasic(ReadOnlySpan<byte> cell8Rows, out char ascii, out bool inverted)
    {
        ulong sig = ComputeBasicSignature(cell8Rows);
        if (BasicSignatures.TryGetValue(sig, out var match))
        {
            ascii = match.Ascii;
            inverted = match.Inverted;
            return true;
        }
        ascii = '\0';
        inverted = false;
        return false;
    }

    public static bool MatchCpm(ReadOnlySpan<byte> leftNibbles, ReadOnlySpan<byte> rightNibbles, out char leftAscii, out char rightAscii)
    {
        uint leftSig = ComputeCpmNibbleSignature(leftNibbles);
        uint rightSig = ComputeCpmNibbleSignature(rightNibbles);
        bool leftOk = CpmSignatures.TryGetValue(leftSig, out leftAscii);
        bool rightOk = CpmSignatures.TryGetValue(rightSig, out rightAscii);
        if (leftOk && rightOk) return true;
        leftAscii = '\0';
        rightAscii = '\0';
        return false;
    }

    public static ushort[] GetBasic16x16Glyph(char ascii)
    {
        int index = ascii - 32;
        if (index >= 0 && index < 96) return Basic16x16Glyphs[index];
        return Basic16x16Glyphs[0]; // space
    }

    public static byte[] GetCpm8x16Glyph(char ascii)
    {
        int index = ascii - 32;
        if (index >= 0 && index < 96) return Cpm8x16Glyphs[index];
        return Cpm8x16Glyphs[0]; // space
    }

    private static ushort[] GenerateBasic16x16(ReadOnlySpan<byte> rom8x8)
    {
        var outGlyph = new ushort[16];

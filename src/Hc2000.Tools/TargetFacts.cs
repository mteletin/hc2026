using System.Globalization;
using System.Text;
using Hc2000.Asm;
using Hc2000.Machine.Capabilities;

namespace Hc2000.Tools;

/// <summary>The machine facts a target's <c>src-library/shared/targets/&lt;name&gt;/targets.inc</c> carries
/// (decision hc2000-asm-library-build-v1, contract §3), written from the records the running machine answers with.</summary>
public static class TargetFacts
{
    /// <summary>The supplied CP/M 2.2's BIOS jump table and BDOS entry on the HC2000 (CPM22-HC.DSK, the machine guide in
    /// src-library/machine); a boot test reads both from page zero at the A&gt; prompt.</summary>
    public const int BiosBase = 0xD300, BdosEntry = 0xC506;

    /// <summary>The machine facts for one target, as <c>shared/targets/&lt;name&gt;/targets.inc</c> holds them, written
    /// from the same records the running machine answers with: the identity bank's ports and capability bits come from
    /// <see cref="IdentityRecord"/>, so a program built for a target and one that probes the bank at run time read the
    /// same numbers (contract §3). The checked-in file is this text; a test fails when the two differ.</summary>
    public static string TargetsInc(LibraryTarget target)
    {
        var text = new StringBuilder();
        void Line(string line = "") => text.Append(line).Append('\n');
        void Equ(string name, int value, string what) =>
            Line($"{name,-20} EQU 0x{value.ToString("X4", CultureInfo.InvariantCulture)}   ; {what}");
        Line("; ===========================================================================");
        Line($"; targets.inc -- the machine facts for target {target.Name}");
        Line(";");
        Line($"; What it is:  {target.Meaning}.");
        Line(";              Generated by hc build --facts from the records the");
        Line(";              running machine answers with; do not edit.");
        Line(";              A test fails when this file and the generator differ.");
        Line("; Builds:      nothing; INCLUDE it once, before code that tests the facts.");
        Line("; Interface:   the EQUs below. A program that runs on several targets");
        Line(";              reads facts from here, not from IF TARGET = n ladders.");
        Line("; ===========================================================================");
        Line();
        Line("; The target");
        foreach (var each in LibraryTargets.All) Equ("TARGET_ID_" + each.Name.ToUpperInvariant().Replace('-', '_'), each.Id, each.Meaning);
        Equ("TARGET_ID", target.Id, $"this file's target, {target.Name}");
        Line();
        if (target.Built)
        {
            Line("; CP/M 2.2 as the HC2000 loads it (the extended BIOS keeps the jump table");
            Line("; where the supplied one has it). A program that must follow a relocated");
            Line("; system reads (0x0001) and (0x0006) at run time instead.");
            Equ("BIOS_BASE", BiosBase, "the BIOS jump table: (0x0001) - 3 after boot");
            Equ("BDOS_ENTRY", BdosEntry, "the BDOS entry: (0x0006) after boot");
        }
        else Line("; CP/M 3.0's memory facts come with the CP/M 3 work; nothing is built here yet.");
        Line();
        var bank = target.Id != 1;
        Line("; The identity bank (decision hc2000-machine-identity-bank-v1)");
        Equ("ID_PRESENT", bank ? 1 : 0, bank ? "the target's machines answer the bank" : "the faithful machine has no bank");
        Equ("ID_PORT_FIRST", IdentityRecord.FirstPort, "byte n is at ID_PORT_FIRST + n * ID_PORT_STRIDE");
        Equ("ID_PORT_STRIDE", 0x0100, "the bank's ports step by 256");
        Equ("ID_LAYOUT", IdentityRecord.LayoutVersion, "record layout version");
        Equ("ID_MODEL_HC2000", IdentityRecord.ModelHc2000, "byte 5 on an HC2000");
        Line();
        Line("; Capability bits, record bytes 7-10 low byte first; a program tests them");
        Line("; at run time, since one target covers several fitted machines");
        foreach (var (bit, name, _, _) in IdentityRecord.Bits)
            Equ("CAP_" + name.ToUpperInvariant().Replace('-', '_'), bit, $"bit {bit}: {name}");
        return text.ToString();
    }
}

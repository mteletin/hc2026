using Hc2000.Asm;
using Hc2000.Machine.Memory;
using Hc2000.Z80;
using Xunit;
using Cpu = Hc2000.Z80.Z80;

namespace Hc2000.Machine.Tests;

// CPU-executed firmware with the production memory/window/session; not the CP/M boot witness.
[Collection("tape-paged-session")]
public sealed class TapeGuestBiosTests
{
    internal static AssemblyResult Assemble()
    {
        var path = Path.Combine(StorageAssetTests.Root(), "bios/src/hc2000/upgrade/tape.init.asm");
        var result = Assembler.AssembleText(File.ReadAllText(path), file: path);
        Assert.True(result.Success, string.Join("; ", result.Diagnostics.Select(d => d.Message)));
        return result;
    }

    [Fact]
    public void ResidentCannotEvictItselfAndFitsBelowThePlainPagedWindow()
    {
        var a = Assemble();
        Assert.Equal(0x6000, a.Symbols["TapeResidentStart"]);
        Assert.True(a.Symbols["TapeCodeEnd"] < 0x7000);
        Assert.True(a.Symbols["TapePayloadEnd"] < 0x6000);
        Assert.InRange(a.Symbols["TapeStackTop"], 0x7400, 0x8000);
    }

    [Theory]
    [InlineData(false, false)]
    [InlineData(false, true)]
    [InlineData(true, false)]
    [InlineData(true, true)]
    public void GuestSectorStoresReachSessionAndRestoreLatchesStackAndIff(bool protectedVolume, bool interrupts)
    {
        var r = new TapeVolumeSessionTests.Rig(protectedVolume);
        Assert.True(r.Session.Mount("VOL1.DSK", 'G').Success);
        var a = Assemble();
        var bus = new Bus(r.Memory);
        r.Memory.SetCpm(true);
        // Install only the resident for this isolated BIOS-entry test.
        var image = a.ToBinary();
        var payload = a.Symbols["TapePayload"] - 0x100;
        for (var i = 0; i < a.Symbols["TapePayloadEnd"] - a.Symbols["TapePayload"]; i++)
            bus.Write((ushort)(0x6000 + i), image[payload + i]);
        // The descriptor was generated by the production owner Bind, not this test.
        Assert.Equal(0x7400, a.Symbols["TapeDescriptor"]);
        bus.Write((ushort)a.Symbols["TapeSelected"], 6);
        bus.Word(a.Symbols["TapeSectorValue"], 3);
        bus.Word(0xD875, 0x4000);
        for (var i = 0; i < 128; i++) bus.Write((ushort)(0x4000 + i), (byte)i);
        r.Memory.WritePagedPort(0x7dfd, 0);
        r.Memory.WritePagedPort(0x7efd, 17);
        var before = r.Memory.Latches;
        var cpu = Run(bus, (ushort)a.Symbols["TapeWrite"], interrupts);
        Assert.Equal(protectedVolume ? 1 : 0, cpu.R.A);
        Assert.Equal(!protectedVolume, r.Session.Dirty);
        Assert.Equal(protectedVolume ? (byte)0xe5 : (byte)1, r.Session.Read(3 * 128 + 1));
        Assert.Equal(before, r.Memory.Latches);
        Assert.Equal(interrupts, cpu.R.IFF1);
        Assert.Equal((ushort)0x5002, cpu.R.SP);
        Assert.All(bus.Ports, p => Assert.Contains(p, new ushort[] { 0x7ffd, 0x7efd, 0x7dfd }));
        cpu = Run(bus, (ushort)a.Symbols["TapeRead"], interrupts);
        Assert.Equal(0, cpu.R.A);
        Assert.Equal(protectedVolume ? (byte)0xe5 : (byte)1, bus.Read(0x4001));
        Assert.Equal(before, r.Memory.Latches);
        // A new value cannot be accepted after a side change: production claim drops it.
        r.Deck.Flip();
        bus.Write(0x4001, 0x77);
        Assert.Equal(1, Run(bus, (ushort)a.Symbols["TapeWrite"], interrupts).R.A);
        Assert.Equal(before, r.Memory.Latches);
        r.Session.Cancel();
        bus.Ports.Clear();
        Assert.Equal(1, Run(bus, (ushort)a.Symbols["TapeRead"], interrupts).R.A);
        Assert.Empty(bus.Ports); // Descriptor refusal happens before any remap.
        Assert.Equal(0x77, bus.Read(0x4001));
    }

    internal static Cpu Run(Bus bus, ushort entry, bool interrupts = true)
    {
        var cpu = new Cpu(bus);
        cpu.R.PC = entry; cpu.R.SP = 0x5000;
        cpu.R.IFF1 = interrupts; cpu.R.IFF2 = interrupts;
        bus.Word(0x5000, 0x80);
        for (var n = 0; cpu.R.PC != 0x80 && n < 100000; n++) cpu.Step();
        Assert.Equal((ushort)0x80, cpu.R.PC);
        return cpu;
    }

    internal sealed class Bus(HcMemory memory) : IBus
    {
        internal List<ushort> Ports { get; } = [];
        internal void Word(int address, int value) { Write((ushort)address, (byte)value); Write((ushort)(address + 1), (byte)(value >> 8)); }
        public byte Read(ushort address) => memory.Read(address);
        public void Write(ushort address, byte value) => memory.Write(address, value);
        public byte In(ushort port) => memory.ReadPagedPort(port);
        public void Out(ushort port, byte value) { Ports.Add(port); memory.WritePagedPort(port, value); }
        public byte IntVector() => 0xff;
        public void Contend(ushort address, int tstates) { }
    }
}

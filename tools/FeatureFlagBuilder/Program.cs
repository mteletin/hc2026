// Build-host generator for the release feature flags: one declared catalog (build/feature-flags.json) gives the typed
// IDs the code gates on and the hc2000-features.json payload that ships beside each executable.
//   FeatureFlagBuilder ids <catalog> <compiled> <out.cs>
//   FeatureFlagBuilder payload <catalog> <compiled> <enabled> <out.json>
// <compiled> and <enabled> are ';'-separated epic slugs. Enabled must be within compiled, compiled within declared.
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

try
{
    if (args.Length < 4) throw new FlagError("usage: FeatureFlagBuilder ids <catalog> <compiled> <out.cs> | payload <catalog> <compiled> <enabled> <out.json>");
    var declared = Catalog(args[1]);
    var compiled = Subset(args[2], declared, "compiled", "declared in " + Path.GetFileName(args[1]));
    switch (args[0])
    {
        case "ids" when args.Length == 4:
            Write(args[3], Ids(declared, compiled));
            return 0;
        case "payload" when args.Length == 5:
            var enabled = Subset(args[3], compiled, "enabled", "compiled (Hc2000CompiledFeatures)");
            Write(args[4], "{\"schemaVersion\":1,\"flagsOn\":[" + string.Join(',', enabled.Select(slug => "\"" + slug + "\"")) + "]}\n");
            return 0;
        default:
            throw new FlagError("unknown mode " + args[0]);
    }
}
catch (FlagError error)
{
    Console.Error.WriteLine("feature-flags: error: " + error.Message);
    return 1;
}

static string[] Catalog(string path)
{
    JsonDocument document;
    try { document = JsonDocument.Parse(File.ReadAllText(path)); }
    catch (Exception error) when (error is JsonException or IOException) { throw new FlagError($"{path} cannot be read: {error.Message}"); }
    using (document)
    {
        var root = document.RootElement;
        if (root.ValueKind != JsonValueKind.Object || !root.TryGetProperty("schemaVersion", out var version) || version.ValueKind != JsonValueKind.Number || version.GetInt32() != 1)
            throw new FlagError($"{path}: schemaVersion must be 1");
        if (!root.TryGetProperty("features", out var features) || features.ValueKind != JsonValueKind.Array)
            throw new FlagError($"{path}: features must be a list of epic slugs");
        var slugs = new List<string>();
        foreach (var item in features.EnumerateArray())
        {
            var slug = item.ValueKind == JsonValueKind.String ? item.GetString()! : "";
            if (!Regex.IsMatch(slug, "^[a-z][a-z0-9]*(-[a-z0-9]+)*$")) throw new FlagError($"{path}: '{slug}' is not a lower-case kebab-case epic slug");
            if (slugs.Contains(slug, StringComparer.Ordinal)) throw new FlagError($"{path}: '{slug}' is declared twice");
            if (slugs.Any(other => Symbol(other) == Symbol(slug))) throw new FlagError($"{path}: '{slug}' has the same build symbol as another slug");
            slugs.Add(slug);
        }
        return slugs.Order(StringComparer.Ordinal).ToArray();
    }
}

static string[] Subset(string list, string[] within, string what, string where)
{
    var slugs = list.Split(';', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
    foreach (var slug in slugs)
    {
        if (!within.Contains(slug, StringComparer.Ordinal)) throw new FlagError($"{what} feature '{slug}' is not {where}");
        if (slugs.Count(other => other == slug) > 1) throw new FlagError($"{what} feature '{slug}' is listed twice");
    }
    return slugs.Order(StringComparer.Ordinal).ToArray();
}

static string Symbol(string slug) => "HC2000_FEATURE_" + slug.ToUpperInvariant().Replace('-', '_');

static string Member(string slug) => string.Concat(slug.Split('-').Select(part => char.ToUpperInvariant(part[0]) + part[1..]));

static string Ids(string[] declared, string[] compiled)
{
    var code = new StringBuilder("// <auto-generated/> From build/feature-flags.json by tools/FeatureFlagBuilder.\nnamespace Hc2000.Features;\n\npublic static partial class Features\n{\n");
    foreach (var slug in declared)
        code.Append($"    /// <summary>Epic {slug}; build symbol {Symbol(slug)}.</summary>\n    public static FeatureId {Member(slug)} {{ get; }} = new(\"{slug}\", {(compiled.Contains(slug) ? "true" : "false")});\n\n");
    code.Append("    /// <summary>Every declared flag.</summary>\n    public static IReadOnlyList<FeatureId> Declared { get; } = [" + string.Join(", ", declared.Select(Member)) + "];\n}\n");
    return code.ToString();
}

static void Write(string path, string text)
{
    Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(path))!);
    if (!File.Exists(path) || File.ReadAllText(path) != text) File.WriteAllText(path, text);
}

sealed class FlagError(string message) : Exception(message);

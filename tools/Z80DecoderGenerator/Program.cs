using System.Security.Cryptography;
using System.Text;
using Hc2000.Z80;

if (args.Length != 1) throw new ArgumentException("Pass the output Z80.Decoder.g.cs path (Base switch emitted alongside it).");
var catalog = new Opcodes();
var entries = catalog.Entries.OrderBy(e => e.DecoderKey.PrefixFamily).ThenBy(e => e.DecoderKey.Opcode).ToArray();
// Prove that observed prefix family/final opcode already IS the concrete key.
// Aliases must never become normalized keys. Prefix consumption remains in CPU.
foreach (var e in entries)
{
    var family = PrefixFamily.Base;
    var pos = 0;
    while (e.Encoding[pos] is 0xdd or 0xfd)
        family = e.Encoding[pos++] == 0xdd ? PrefixFamily.DD : PrefixFamily.FD;
    if (e.Encoding[pos] == 0xcb)
    {
        if (family == PrefixFamily.Base) { family = PrefixFamily.CB; pos++; }
        else { family = family == PrefixFamily.DD ? PrefixFamily.DDCB : PrefixFamily.FDCB; pos += 2; }
    }
    else if (e.Encoding[pos] == 0xed) { family = PrefixFamily.ED; pos++; }
    var observed = new DecoderKey(family, e.Encoding[pos]);
    if (observed != e.DecoderKey || catalog[observed].DecoderKey != observed)
        throw new InvalidOperationException($"Catalog key is not an observed concrete encoding: {e.Pattern}");
}
var nop = catalog[new DecoderKey(PrefixFamily.Base, 0)];
if (nop.Pattern != "NOP" || nop.Length != 1 || nop.Operands.Count != 0)
    throw new InvalidOperationException("The M1-only NOP specialization no longer matches the catalog.");
var signature = string.Join('\n', entries.Select(e => $"{e.DecoderKey.PrefixFamily}|{e.DecoderKey.Opcode:X2}|{e.Pattern}|{Convert.ToHexString(e.Encoding.ToArray())}|{e.CanonicalForAssembly}|{string.Join(';', e.Operands.Select(s => $"{s.Kind}:{s.ByteOffset}:{s.PatternToken}"))}"));
var hash = Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(signature)));
var output = $$"""
// Generated by tools/Z80DecoderGenerator from the instance-owned Opcodes catalog.
// The generator verifies every concrete encoding and the M1-only NOP invariant.
namespace Hc2000.Z80;

public sealed partial class Z80
{
    internal const string ExecutionCatalogSha256 = "{{hash}}";
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]
    internal DecoderKey DecodeExecutionKey(PrefixFamily family, byte opcode) => new(family, opcode);
}
""";
File.WriteAllText(args[0], output.Replace("\r\n", "\n", StringComparison.Ordinal) + "\n");

var baseEntries = entries.Where(e => e.DecoderKey.PrefixFamily == PrefixFamily.Base).ToArray();
var generated = new StringBuilder("// Generated from Opcodes by tools/Z80DecoderGenerator; do not edit cases.\nnamespace Hc2000.Z80;\n\npublic sealed partial class Z80\n{\n");
generated.AppendLine($"    internal const string GeneratedBaseOpcodes = \"{string.Join(',', baseEntries.Select(e => e.DecoderKey.Opcode.ToString("X2")))}\";");
generated.AppendLine("    private void ExecuteGeneratedBase(byte opcode, byte previousQ)\n    {\n        switch (opcode)\n        {");
foreach (var e in baseEntries)
    generated.AppendLine($"            case 0x{e.DecoderKey.Opcode:x2}: {{ {Body(e.DecoderKey.Opcode)} return; }} // {e.Pattern}");
generated.AppendLine("            default: throw new ArgumentOutOfRangeException(nameof(opcode));\n        }\n    }\n}");
File.WriteAllText(Path.Combine(Path.GetDirectoryName(args[0])!, "Z80.Base.g.cs"), generated.ToString().Replace("\r\n", "\n", StringComparison.Ordinal));

// Constant-fold the existing switch's operand selections for each catalog key.
// These are semantic helper selectors, not an independent opcode inventory.
string Body(byte opcode)
{
    string[] regs = ["R.B", "R.C", "R.D", "R.E", "R.H", "R.L", "ReadMemory(R.HL)", "R.A"];
    string[] pairs = ["R.BC", "R.DE", "R.HL", "R.SP"];
    var x = opcode >> 6; var y = (opcode >> 3) & 7; var z = opcode & 7;
    var p = y >> 1; var q = y & 1;
    if (opcode == 0) return "";
    if (x == 2) return $"Alu({y}, {regs[z]});";
    if (x == 3 && z == 6) return $"Alu({y}, ReadImmediate());";
    if (x == 0 && z is 4 or 5)
        return y == 6
            ? $"var address = R.HL; var value = ReadMemory(address); Idle(address, 1); WriteMemory(address, IncDec(value, {(z == 5 ? "true" : "false")}));"
            : $"{regs[y]} = IncDec({regs[y]}, {(z == 5 ? "true" : "false")});";
    if (x == 0 && z == 1 && q == 1) return $"Add16({p}, PrefixFamily.Base);";
    if (x == 0 && z == 3) return $"Idle((ushort)((R.I << 8) | R.R), 2); {pairs[p]} = unchecked((ushort)({pairs[p]} {(q == 0 ? "+" : "-")} 1));";
    if (x == 0 && z == 1 && q == 0) return $"{pairs[p]} = ReadWordImmediate();";
    if (x == 0 && z == 6) return y == 6 ? "WriteMemory(R.HL, ReadImmediate());" : $"{regs[y]} = ReadImmediate();";
    if (x == 1)
    {
        if (opcode == 0x76) return "Halted = true;";
        if (y == z) return "";
        return y == 6 ? $"WriteMemory(R.HL, {regs[z]});" : $"{regs[y]} = {regs[z]};";
    }
    if (x == 0 && z == 7) return $"ExecuteAccumulatorMisc({y}, previousQ);";
    if (x == 3)
    {
        var ir = "(ushort)((R.I << 8) | R.R)";
        if (z == 0) return $"Idle({ir}, 1); if (Condition({y})) R.PC = R.WZ = Pop();";
        if (z == 1)
        {
            if (q == 0) return $"{(p == 3 ? "R.AF" : pairs[p])} = Pop();";
            return p switch
            {
                0 => "R.PC = R.WZ = Pop();",
                1 => "(R.BC, R.BCShadow) = (R.BCShadow, R.BC); (R.DE, R.DEShadow) = (R.DEShadow, R.DE); (R.HL, R.HLShadow) = (R.HLShadow, R.HL);",
                2 => "R.PC = R.HL;",
                _ => $"Idle({ir}, 2); R.SP = R.HL;"
            };
        }
        if (z == 2) return $"R.WZ = ReadWordImmediate(); if (Condition({y})) R.PC = R.WZ;";
        if (z == 3) return y switch
        {
            0 => "R.PC = R.WZ = ReadWordImmediate();",
            2 => "var n = ReadImmediate(); var port = (ushort)((R.A << 8) | n); Output(port, R.A); R.WZ = (ushort)((port & 0xff00) | ((n + 1) & 255));",
            3 => "var n = ReadImmediate(); var port = (ushort)((R.A << 8) | n); R.A = Input(port); R.WZ = unchecked((ushort)(port + 1));",
            4 => "var low = ReadMemory(R.SP); var highAddress = unchecked((ushort)(R.SP + 1)); var high = ReadMemory(highAddress); Idle(highAddress, 1); var old = R.HL; WriteMemory(highAddress, (byte)(old >> 8)); WriteMemory(R.SP, (byte)old); Idle(R.SP, 2); R.HL = R.WZ = (ushort)(low | (high << 8));",
            5 => "(R.DE, R.HL) = (R.HL, R.DE);",
            6 => "R.IFF1 = R.IFF2 = false; eiDelay = 0;",
            7 => "R.IFF1 = R.IFF2 = true; eiDelay = 2;",
            _ => throw new InvalidOperationException("Prefix escape is not a Base case.")
        };
        if (z == 4) return $"R.WZ = ReadWordImmediate(); if (Condition({y})) {{ Idle(unchecked((ushort)(R.PC - 1)), 1); Push(R.PC); R.PC = R.WZ; }}";
        if (z == 5) return q == 0
            ? $"Idle({ir}, 1); Push({(p == 3 ? "R.AF" : pairs[p])});"
            : "R.WZ = ReadWordImmediate(); Idle(unchecked((ushort)(R.PC - 1)), 1); Push(R.PC); R.PC = R.WZ;";
        if (z == 7) return $"Idle({ir}, 1); Push(R.PC); R.PC = R.WZ = 0x{y * 8:x2};";
    }
    if (x == 0 && z == 0)
    {
        if (y == 1) return "(R.AF, R.AFShadow) = (R.AFShadow, R.AF);";
        var prefix = y == 2 ? "Idle((ushort)((R.I << 8) | R.R), 1); R.B--; " : "";
        var condition = y == 2 ? "R.B != 0" : y == 3 ? "true" : $"Condition({y - 4})";
        return prefix + $"var displacement = (sbyte)ReadImmediate(); if ({condition}) {{ Idle(unchecked((ushort)(R.PC - 1)), 5); R.PC = R.WZ = unchecked((ushort)(R.PC + displacement)); }}";
    }
    // The remaining memory transfers already have an index-aware shared helper.
    return $"ExecuteControl(new DecoderKey(PrefixFamily.Base, 0x{opcode:x2}));";
}
